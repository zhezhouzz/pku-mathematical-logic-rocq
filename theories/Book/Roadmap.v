(** * Course Roadmap

    The dependency path through the book is intentionally linear at first:

    [[
      Rocq primer
          |
      preliminary mathematics
          |
      propositional syntax -- semantics -- N -- P
          |
      first-order syntax -- N_L -- K_L -- semantics
    ]]

    Natural-deduction derived rules depend on the primitive rules of system N.
    The Hilbert systems are independent of natural deduction, so they can also
    be studied as an alternative branch.  Semantic chapters do not depend on
    the proof systems.  This separation makes the still-unproved connections
    -- soundness, completeness, and equivalence of calculi -- visible rather
    than silently assuming them.

    The online table of contents records the exact correspondence with
    Sections 1.1--3.8 of the textbook. *)
